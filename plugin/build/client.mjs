/**
 * Build this package's `lib/` half.
 *
 * The Host entry forwards to `src/`, so the Host logic exists once.
 *
 * The client entry must be ONE self-contained bundle: DSH's client module
 * system loads a single `client.js` per package and its synchronous `require`
 * may not reach another relative `client*.js`. Platform singletons (React,
 * react-dom, Cordis) stay as `require('react')` calls because the shell's
 * frozen module table answers them.
 *
 * The bundler below is deliberately minimal: it inlines relative CommonJS
 * requires only, needs no third-party dependency, and therefore builds offline.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..')
const lib = path.join(root, 'lib')

/** The id under which the client module system registers this bundle. */
const PACKAGE_ID = 'dsh-plugin-session-cleaner'

/** Matches `require('./x.js')` / `require("../y")` but never a bare specifier. */
const RELATIVE_REQUIRE = /require\(\s*(['"])(\.{1,2}\/[^'"]+)\1\s*\)/g

/** Resolve a relative request against its importer, adding `.js` when omitted. */
function resolveRelative(fromFile, request) {
  const base = path.resolve(path.dirname(fromFile), request)
  if (path.extname(base) !== '') return base
  return `${base}.js`
}

/** Key a module by its repo-relative POSIX path, for stable generated output. */
const keyOf = (file) => path.relative(root, path.resolve(file)).replaceAll('\\', '/')

/**
 * Inline every relative require reachable from the entry.
 * @returns one JavaScript expression evaluating to the entry's `module.exports`.
 */
async function bundle(entry) {
  const modules = new Map()

  async function visit(file) {
    const resolved = path.resolve(file)
    const key = keyOf(resolved)
    if (modules.has(key)) return
    // Reserve before recursing so a cycle terminates instead of looping.
    modules.set(key, undefined)

    const source = await readFile(resolved, 'utf8')
    const dependencies = new Map()
    for (const match of source.matchAll(RELATIVE_REQUIRE)) {
      const target = resolveRelative(resolved, match[2])
      dependencies.set(match[2], keyOf(target))
    }
    for (const target of dependencies.values()) await visit(path.join(root, target))

    // A module is only ever required as a value, so returning `module.exports`
    // from an IIFE reproduces CommonJS semantics without a registry at runtime.
    const body = source.replace(RELATIVE_REQUIRE, (_match, _quote, request) => {
      const targetKey = dependencies.get(request)
      return `__modules[${JSON.stringify(targetKey)}]`
    })
    const wrapped = `__modules[${JSON.stringify(key)}] = (() => {\n`
      + 'const module = { exports: {} };\nconst exports = module.exports;\n'
      + `${body}\nreturn module.exports;\n})();`

    // Emit AFTER the dependencies so their assignments run first: a recipient
    // reads `__modules[...]` at its own top level, which would be undefined if
    // it were defined ahead of the module it requires.
    modules.delete(key)
    modules.set(key, wrapped)
  }

  await visit(entry)

  // Emission order is dependency-first. A remaining placeholder means a real
  // require cycle, which this bundler deliberately does not support.
  const parts = []
  for (const [key, wrapped] of modules) {
    if (wrapped === undefined) throw new Error(`client bundle: relative require cycle through ${key}`)
    parts.push(wrapped)
  }

  const entryKey = keyOf(entry)
  // DSH's client module system registers plugin bundles through the
  // `window.__ModuleLoader__` queue facade: each bundle calls load() with its
  // package id and a `factory(require)` that returns the plugin's exports
  // (materialized lazily, memoized by the module system).
  return 'window.__ModuleLoader__.load({id:'
    + `${JSON.stringify(PACKAGE_ID)},factory:function(require){\n`
    + 'const __modules = {};\n'
    + parts.join('\n')
    + `\nreturn __modules[${JSON.stringify(entryKey)}](require);\n`
    + '}});\n'
}

await mkdir(lib, { recursive: true })

await writeFile(
  path.join(lib, 'index.js'),
  '// Generated by build/client.mjs — the Host half lives in ../src/index.js.\nexport * from \'../src/index.js\'\n',
  'utf8',
)

await writeFile(
  path.join(lib, 'remote.js'),
  '// Generated by build/client.mjs — the contract lives in ../src/contract.cjs.\nexport * from \'../src/contract.cjs\'\nexport { default } from \'../src/contract.cjs\'\n',
  'utf8',
)

// dsh-typert-loader imports `./typert` for every bundle that declares it; the
// export MUST resolve, so the forwarder ships with the package.
await writeFile(
  path.join(lib, 'typert.host.js'),
  '// Generated by build/client.mjs — the reflection lives in ../src/typert.host.js.\nexport * from \'../src/typert.host.js\'\nexport { default } from \'../src/typert.host.js\'\n',
  'utf8',
)

const bundled = await bundle(path.join(root, 'client', 'client.js'))
await writeFile(path.join(lib, 'client.js'), `// Generated by build/client.mjs — do not edit. Source lives in ../client/.\n${bundled}`, 'utf8')

console.log('built lib/index.js, lib/remote.js, lib/typert.host.js and lib/client.js')
